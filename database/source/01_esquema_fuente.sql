-- ===================== trigger last_edited_when =====================
-- En cada UPDATE, si quien modifica no fijó last_edited_when explícitamente,
-- se registra la hora actual. Garantiza que la extracción incremental detecte
-- TODO cambio, incluso uno hecho a mano durante la demo.

CREATE OR REPLACE FUNCTION application.fn_actualizar_last_edited_when()
RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.last_edited_when IS NOT DISTINCT FROM OLD.last_edited_when THEN
        NEW.last_edited_when := clock_timestamp();
    END IF;
    RETURN NEW;
END;
$$;

DO $$
DECLARE
    tabla text;
BEGIN
    FOREACH tabla IN ARRAY ARRAY[
        'application.people', 'application.countries', 'application.state_provinces',
        'application.cities', 'application.delivery_methods',
        'warehouse.colors', 'warehouse.package_types', 'warehouse.stock_groups',
        'warehouse.stock_items', 'warehouse.stock_item_stock_groups',
        'sales.buying_groups', 'sales.customer_categories', 'sales.customers',
        'sales.orders', 'sales.order_lines', 'sales.invoices', 'sales.invoice_lines'
    ] LOOP
        EXECUTE format(
            'CREATE OR REPLACE TRIGGER trg_last_edited_when BEFORE UPDATE ON %s '
            'FOR EACH ROW EXECUTE FUNCTION application.fn_actualizar_last_edited_when()',
            tabla
        );
    END LOOP;
END;
$$;
