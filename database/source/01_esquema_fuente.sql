-- =====================================================================
-- Faro · Esquema de la base OPERACIONAL (fuente): wwi_oltp
-- Simula el sistema transaccional de WideWorldImporters (módulo de ventas).
--
-- IDEMPOTENTE: se puede ejecutar varias veces sin error ni pérdida de datos.
--
-- Convenciones:
--  * Nombres en snake_case (estilo PostgreSQL). La equivalencia con los
--    nombres originales de SQL Server está en el diccionario de datos.
--  * Claves primarias IDENTITY "BY DEFAULT": se conservan los IDs originales
--    y el sistema puede generar IDs nuevos (simulador de ventas).
--  * last_edited_when (timestamptz): fecha/hora de la última modificación.
--    En las tablas temporales de SQL Server proviene de ValidFrom.
--    Un trigger la actualiza en cada UPDATE: es la base de la carga incremental.
--  * Fechas/horas originales sin zona horaria se interpretan como UTC.
--    SQL Server guarda 7 decimales de segundo y PostgreSQL 6 (microsegundos).
--  * Minimización de datos: NO se migran contraseñas, fotos, correos,
--    teléfonos, direcciones ni comentarios de texto libre.
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS application;
CREATE SCHEMA IF NOT EXISTS warehouse;
CREATE SCHEMA IF NOT EXISTS sales;

-- =========================== application ============================

CREATE TABLE IF NOT EXISTS application.people (
    person_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name         varchar(50) NOT NULL,
    preferred_name    varchar(50) NOT NULL,
    is_employee       boolean     NOT NULL,
    is_salesperson    boolean     NOT NULL,
    last_edited_by    integer     NOT NULL REFERENCES application.people (person_id),
    last_edited_when  timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE application.people IS
    'Personas: empleados (incluidos vendedores) y contactos de clientes. Solo datos no sensibles.';

CREATE TABLE IF NOT EXISTS application.countries (
    country_id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_name                varchar(60) NOT NULL,
    formal_name                 varchar(60) NOT NULL,
    iso_alpha3_code             varchar(3),
    iso_numeric_code            integer,
    country_type                varchar(20),
    latest_recorded_population  bigint,
    continent                   varchar(30) NOT NULL,
    region                      varchar(30) NOT NULL,
    subregion                   varchar(30) NOT NULL,
    last_edited_by              integer     NOT NULL REFERENCES application.people (person_id),
    last_edited_when            timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE application.countries IS 'Países.';

CREATE TABLE IF NOT EXISTS application.state_provinces (
    state_province_id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state_province_code         varchar(5)  NOT NULL,
    state_province_name         varchar(50) NOT NULL,
    country_id                  integer     NOT NULL REFERENCES application.countries (country_id),
    sales_territory             varchar(50) NOT NULL,
    latest_recorded_population  bigint,
    last_edited_by              integer     NOT NULL REFERENCES application.people (person_id),
    last_edited_when            timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE application.state_provinces IS 'Estados/provincias, con su territorio de ventas.';

CREATE TABLE IF NOT EXISTS application.cities (
    city_id                     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_name                   varchar(50) NOT NULL,
    state_province_id           integer     NOT NULL REFERENCES application.state_provinces (state_province_id),
    latitude                    double precision,
    longitude                   double precision,
    latest_recorded_population  bigint,
    last_edited_by              integer     NOT NULL REFERENCES application.people (person_id),
    last_edited_when            timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE application.cities IS
    'Ciudades. latitude/longitude provienen del tipo geography (Location) de SQL Server.';

CREATE TABLE IF NOT EXISTS application.delivery_methods (
    delivery_method_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_method_name  varchar(50) NOT NULL,
    last_edited_by        integer     NOT NULL REFERENCES application.people (person_id),
    last_edited_when      timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE application.delivery_methods IS 'Métodos de entrega.';

-- ============================ warehouse =============================

CREATE TABLE IF NOT EXISTS warehouse.colors (
    color_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    color_name        varchar(20) NOT NULL,
    last_edited_by    integer     NOT NULL REFERENCES application.people (person_id),
    last_edited_when  timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE warehouse.colors IS 'Colores de producto.';

CREATE TABLE IF NOT EXISTS warehouse.package_types (
    package_type_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_type_name  varchar(50) NOT NULL,
    last_edited_by     integer     NOT NULL REFERENCES application.people (person_id),
    last_edited_when   timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE warehouse.package_types IS 'Tipos de empaque (unidad de venta).';

CREATE TABLE IF NOT EXISTS warehouse.stock_groups (
    stock_group_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_group_name  varchar(50) NOT NULL,
    last_edited_by    integer     NOT NULL REFERENCES application.people (person_id),
    last_edited_when  timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE warehouse.stock_groups IS 'Grupos (categorías) de producto.';

CREATE TABLE IF NOT EXISTS warehouse.stock_items (
    stock_item_id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_item_name           varchar(100)  NOT NULL,
    color_id                  integer       REFERENCES warehouse.colors (color_id),
    unit_package_id           integer       NOT NULL REFERENCES warehouse.package_types (package_type_id),
    outer_package_id          integer       NOT NULL REFERENCES warehouse.package_types (package_type_id),
    brand                     varchar(50),
    size                      varchar(20),
    lead_time_days            integer       NOT NULL,
    quantity_per_outer        integer       NOT NULL,
    is_chiller_stock          boolean       NOT NULL,
    tax_rate                  numeric(18,3) NOT NULL,
    unit_price                numeric(18,2) NOT NULL,
    recommended_retail_price  numeric(18,2),
    typical_weight_per_unit   numeric(18,3) NOT NULL,
    last_edited_by            integer       NOT NULL REFERENCES application.people (person_id),
    last_edited_when          timestamptz   NOT NULL DEFAULT now()
);
COMMENT ON TABLE warehouse.stock_items IS 'Productos (artículos de inventario) que se venden.';

CREATE TABLE IF NOT EXISTS warehouse.stock_item_stock_groups (
    stock_item_stock_group_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_item_id              integer     NOT NULL REFERENCES warehouse.stock_items (stock_item_id),
    stock_group_id             integer     NOT NULL REFERENCES warehouse.stock_groups (stock_group_id),
    last_edited_by             integer     NOT NULL REFERENCES application.people (person_id),
    last_edited_when           timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_stock_item_stock_group UNIQUE (stock_item_id, stock_group_id)
);
COMMENT ON TABLE warehouse.stock_item_stock_groups IS
    'Relación MUCHOS a MUCHOS producto-grupo: un producto puede estar en varios grupos.';

